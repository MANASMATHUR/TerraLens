import { NextResponse } from 'next/server';
import fs from 'fs';
import path from 'path';
import { supabaseAdmin } from '@/lib/supabase/server';
import { IncidentWithContext } from '@/types';

export const dynamic = 'force-dynamic';

export async function GET() {
  try {
    // 1. Try Supabase first if available
    if (supabaseAdmin) {
      const { data: incidents, error: incErr } = await supabaseAdmin
        .from('incidents')
        .select(`
          id, scenario_id, incident_type, title, description,
          severity_score, duration_hours, impact_radius_m, geometry, is_synthetic,
          context:incident_context (*)
        `)
        .eq('scenario_id', 'jaipur_monsoon_2026')
        .order('id');

      if (!incErr && incidents && incidents.length > 0) {
        return NextResponse.json(incidents as unknown as IncidentWithContext[]);
      }
    }

    // 2. Fallback to cached static JSON generated by Python pipeline
    const jsonPath = path.join(process.cwd(), 'public', 'geo', 'incidents_data.json');
    if (fs.existsSync(jsonPath)) {
      const fileData = fs.readFileSync(jsonPath, 'utf8');
      const incidentsRaw = JSON.parse(fileData);

      // Ensure geometry.coordinates is populated
      const incidents = incidentsRaw.map((inc: any) => ({
        ...inc,
        geometry: inc.geometry || {
          type: 'Point',
          coordinates: [inc.lon, inc.lat],
        },
      }));

      return NextResponse.json(incidents);
    }

    return NextResponse.json({ error: 'Incidents data not found' }, { status: 404 });
  } catch (error) {
    console.error('Error in GET /api/incidents:', error);
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 });
  }
}
